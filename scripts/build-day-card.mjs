/**
 * Builds the day card's page (chat connection spec 2.3): esbuild bundles
 * `server/src/chat/card/view.ts` (the markup, the handshake and the styles) into one script, and the
 * script goes into a small HTML shell. Run as `npm run chat:card`, it writes the page into
 * `server/src/chat/card/dayCard.generated.ts`, which the MCP route serves; the build test fails when
 * that file is not what the source builds to, so run it after any change under `server/src/chat/card`
 * (or to the palettes in `app/src/theme.ts`), and commit the result.
 *
 * The page is the same text on every machine: nothing in it is a date, a path or a version.
 * The shell holds the doctype, `<html lang="he" dir="rtl">`, a meta charset and viewport, the empty
 * `<div id="card">` and the inline script. The script adds its own styles when it starts.
 *
 * esbuild comes with vitest and tsup; it is not a dependency of its own. A new esbuild can minify
 * differently: run this again after upgrading either.
 */
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ENTRY = fileURLToPath(new URL('../server/src/chat/card/view.ts', import.meta.url));
const OUTPUT = fileURLToPath(new URL('../server/src/chat/card/dayCard.generated.ts', import.meta.url));

const HEADER = `/**
 * GENERATED by scripts/build-day-card.mjs (npm run chat:card). Do not edit by hand: change
 * server/src/chat/card/ (markup, styles, bridge, view), run \`npm run chat:card\`, and commit this file.
 * A test fails when it is out of date.
 */
`;

/** Script text that can sit in a <script> element: it cannot hold the end of the element, whatever string it is in. */
export function scriptSafe(script) {
  return script.replace(/<\/(script)/gi, '<\\/$1');
}

/** The day card's page: one HTML document, with its script and no other resource. */
export async function buildDayCard() {
  const { outputFiles } = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    charset: 'utf8',
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  const script = scriptSafe(outputFiles[0].text.trim());
  return (
    '<!doctype html>' +
    '<html lang="he" dir="rtl"><head>' +
    '<meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width, initial-scale=1">' +
    '</head><body>' +
    '<div id="card"></div>' +
    `<script>${script}</script>` +
    '</body></html>'
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = await buildDayCard();
  await writeFile(OUTPUT, `${HEADER}export const DAY_CARD_HTML = ${JSON.stringify(html)};\n`, 'utf8');
  console.log(`dayCard.generated.ts: ${html.length} characters`);
}
